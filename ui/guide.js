function guideNode(tag, text, cls) {
  const el = document.createElement(tag);
  if (text) el.textContent = text;
  if (cls) el.className = cls;
  return el;
}

function guideGoTo(id) {
  const sec = document.getElementById("guide-" + id);
  if (!sec) return;
  sec.open = true;
  sec.scrollIntoView({ block: "start" });
}

function guideOpen(id) {
  document.getElementById("guideSearch").value = "";
  guideFilter();
  guideGoTo(id);
}

function guideFilter() {
  const words = document.getElementById("guideSearch").value.trim().toLowerCase().split(/\s+/).filter(Boolean);
  let shown = 0;
  for (const s of GUIDE) {
    const sec = document.getElementById("guide-" + s.id);
    const text = sec.textContent.toLowerCase();
    const hit = words.every((w) => text.includes(w));
    sec.hidden = !hit;
    document.getElementById("guide-toc-" + s.id).hidden = !hit;
    if (words.length) sec.open = hit;
    if (hit) shown++;
  }
  document.getElementById("guideNone").hidden = shown > 0;
}

function initGuide() {
  const toc = document.getElementById("guideToc");
  const body = document.getElementById("guideBody");
  for (const s of GUIDE) {
    const link = guideNode("button", s.title);
    link.type = "button";
    link.id = "guide-toc-" + s.id;
    link.addEventListener("click", () => guideGoTo(s.id));
    toc.appendChild(link);

    const sec = guideNode("details", "", "guide-section");
    sec.id = "guide-" + s.id;
    sec.appendChild(guideNode("summary", s.title));
    for (const b of s.blocks) {
      if (typeof b === "string") { sec.appendChild(guideNode("p", b)); continue; }
      if (b.h) sec.appendChild(guideNode("h3", b.h));
      if (b.warn) sec.appendChild(guideNode("p", "אזהרה: " + b.warn, "guide-box warn"));
      if (b.note) sec.appendChild(guideNode("p", b.note, "guide-box"));
      const items = b.steps || b.list;
      if (items) {
        const ul = guideNode(b.steps ? "ol" : "ul");
        items.forEach((x) => ul.appendChild(guideNode("li", x)));
        sec.appendChild(ul);
      }
    }
    body.appendChild(sec);
  }
  document.getElementById("guideSearch").addEventListener("input", guideFilter);

  // A help link in the header of every feature tab.
  document.querySelectorAll(".panel").forEach((p) => {
    const id = p.id.replace("tab-", "");
    const h1 = p.querySelector("h1");
    if (id === "guide" || !h1) return;
    const row = guideNode("div", "", "panel-head");
    h1.replaceWith(row);
    const help = guideNode("button", "", "help-link");
    help.type = "button";
    help.setAttribute("data-i18n", "guide.help");
    help.addEventListener("click", () => { switchTab("guide"); guideOpen(id); });
    row.append(h1, help);
  });
}
